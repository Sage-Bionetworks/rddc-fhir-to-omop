# Regenerate cdm54_ddl_duckdb.sql from OHDSI CommonDataModel (official CDM 5.4 DDL,
# rendered for DuckDB). Usage: Rscript qa/dqd/make_ddl.R qa/dqd/cdm54_ddl_duckdb.sql
out <- commandArgs(trailingOnly = TRUE)[1]
ddl <- CommonDataModel::createDdl("5.4")
sql <- SqlRender::translate(SqlRender::render(ddl, cdmDatabaseSchema = "cdm"), "duckdb")
# DuckDB reads NUMERIC as DECIMAL(18,3), which rounds lab values and coordinates.
sql <- gsub("\\bNUMERIC\\b", "DOUBLE", sql, ignore.case = TRUE)
header <- sprintf("-- Generated by qa/dqd/make_ddl.R from CommonDataModel %s (CDM 5.4, duckdb dialect).\n-- NUMERIC replaced by DOUBLE. Do not edit by hand.\nCREATE SCHEMA IF NOT EXISTS cdm;\n",
                  packageVersion("CommonDataModel"))
writeLines(c(header, sql), out)
